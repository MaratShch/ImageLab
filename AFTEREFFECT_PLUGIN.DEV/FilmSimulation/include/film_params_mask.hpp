/// @return true when @p control is available for film @p profile.
constexpr bool FilmControlAvailable(const eFILM_PROFILE profile,
                                    const eFILM_CONTROL_BIT control) noexcept
{
    return ((kFilmControlAvailability[
                 static_cast<std::size_t>(profile)]
             >> static_cast<std::uint64_t>(control))
            & 1ull) != 0ull;
}

