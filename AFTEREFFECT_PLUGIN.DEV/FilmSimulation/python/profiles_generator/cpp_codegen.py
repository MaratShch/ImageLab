# Split emission (2026-08-18, owner-approved "Option C")
#
# WHY. film_profiles.cpp had grown to 676 KB of which 656 KB (97%) was ONE
# function: GetFilmDatabase() returning a std::vector<FilmProfile> built from
# a single braced-init-list of 155 elements. FilmProfile holds std::string and
# std::vector members, so that list is not constant data -- the compiler must
# emit constructor code and EH cleanup states for every element inside one
# function, PLUS a const std::initializer_list backing array of 155 full
# FilmProfile temporaries on that function's stack, PLUS a deep COPY of every
# element (initializer_list gives only const access, so the vector cannot
# move from it). MSVC 2015's hard limits (C1060 out of heap, C1026 parser
# stack, pathological optimiser time) are all PER-FUNCTION, and the Intel
# compiler's optimiser degrades the same way, so the owner's VS2015 SP3 + ICC
# environment could not reliably compile it. The primary axis to bound is
# bytes-per-function; bytes-per-TU is secondary (memory headroom, /MP).
#
# WHAT. The database is emitted as:
#   film_profiles_data_01.cpp .. _NN.cpp   consecutive, size-balanced slices
#                                          of FILM_PROFILES; each defines
#                                          detail::AppendProfiles_NN(v) doing
#                                          one v.push_back(FilmProfile{...})
#                                          per profile. push_back of an rvalue
#                                          MOVES -- no init-list backing array,
#                                          no element copies, bounded function
#                                          size.
#   film_profiles_detail.hpp               declares the NN append functions.
#   LoadFilmDataBase.h / .cpp              the explicit-initialisation API the
#                                          owner calls from the effect's
#                                          GlobalSetup (see the .h docstring).
#   film_profiles.cpp                      now small: print stocks, formats,
#                                          and the legacy GetFilmDatabase()
#                                          copy-returning wrapper kept for
#                                          AlgoMemHandler.cpp compatibility.
#
# THE SLOT COUNT IS FIXED at N_DATA_SLOTS and every slot file is ALWAYS
# emitted, empty ones as a no-op function. That is deliberate: the owner's
# VS2015 .vcxproj lists a fixed set of filenames ONCE and never changes as
# the database grows. If the database outgrows the slots, generation FAILS
# LOUDLY telling the owner to raise N_DATA_SLOTS and add the new file to the
# project -- a deliberate manual step, never a silent regression back into
# one giant translation unit.
#
# Enum order is preserved by construction: slots are consecutive slices of
# the emission order, the loader calls the slots in fixed numeric order, and
# film_names.txt / film_enum.hpp are derived by parsing the emitted slot
# files back in that same order (parse_vector_names), so vector index ==
# enum value == names-file line, exactly as before the split.
# ===========================================================================

# ⚠ 16 -> 17 ON 2026-09-02e, AND THIS LINE IS A REQUEST TO THE OWNER, NOT JUST
# AN EDIT. Queue T3 appended three stocks (ids 172-174) and the database crossed
# the per-file ceiling: with 16 slots the smallest achievable high-water is
# 113 458 bytes against SLOT_SOURCE_LIMIT's 112 000 -- over by 1 458 bytes,
# 1.3 %. The generator refused to emit rather than silently regress, which is
# exactly what it was built to do.
#
# ⚠ **`film_profiles_data_17.cpp` MUST BE ADDED TO THE VS2015 .vcxproj BY HAND.**
# Nothing in this repository can do it. If it is missed the plugin fails at LINK
# time with an unresolved `AppendFilmProfiles_17` -- a loud failure, never a
# wrong render or a shifted film index. Every other generated file is unchanged
# in name and count.
#
# WHY NOT SHAVE 1 458 BYTES INSTEAD. It was measured and rejected. The total
# payload is 1 689 598 bytes against a 16-slot capacity of 1 792 000, so the
# database fits ON AVERAGE and fails only on the WORST slot -- the blocks are
# indivisible and the slices must stay consecutive, so the partition is
# quantised by block size (the largest single profile is 39 015 bytes). Trimming
# emitted text to squeeze under a ceiling would buy one or two more stocks and
# would have to be done again, while making the emitter's output a function of
# how close to a limit it happened to be. With 17 slots the high-water drops to
# 104 814 bytes, 93.6 % of the ceiling -- the same headroom the 16-slot layout
# had when it was chosen.
N_DATA_SLOTS = 17          #: fixed; the .vcxproj lists these files once
SLOT_SOURCE_LIMIT = 112_000  #: bytes of emitted source per slot, hard error


def _wrap_push_back(block: str) -> str:
    """One _profile_block() entry -> a v.push_back(FilmProfile{...}) statement.

    The aggregate literal itself is untouched; only the frame changes:
        "        {"    (the entry's opening line)  -> "        v.push_back(FilmProfile{"
        "        },"   (the entry's closing line)  -> "        });"
    Statement-per-profile is the load-bearing property: a sequence of
    independent full-expressions compiles in bounded memory where one
    676 KB braced-init-list expression does not, and each temporary is an
    rvalue so the vector MOVES it (strings and spectral vectors transfer
    their heap blocks instead of duplicating them).
    """
    open_key = "\n        {\n"
    if not block.startswith("        {"):
        i = block.index(open_key)
        block = (block[:i] + "\n        v.push_back(FilmProfile{\n"
                 + block[i + len(open_key):])
    else:
        block = "        v.push_back(FilmProfile{\n" + block[len("        {\n"):]
    if not block.endswith("        },\n"):
        raise ValueError("profile block does not end with '},' -- emitter "
                         "layout changed, update _wrap_push_back")
    return block[:-len("        },\n")] + "        });\n"


def _distribute(blocks: list) -> list:
    """Assign consecutive blocks to N_DATA_SLOTS slots, MINIMISING THE LARGEST.

    WHY THIS CHANGED (2026-08-28)
    -----------------------------
    The previous rule was cumulative-size partitioning: block i went to slot
    floor(bytes_before_i / total * N). That balances the AVERAGE, which is not
    the quantity that matters. What matters is the LARGEST slot, because
    SLOT_SOURCE_LIMIT is a per-file ceiling and the build fails when any single
    slot crosses it -- and crossing it costs an N_DATA_SLOTS bump AND a manual
    .vcxproj edit.

    Measured on the 161-stock database:

        cumulative-size   high-water 109,010 bytes   97.3 % of the limit
        minimise-largest  high-water 104,270 bytes   93.1 %

    4,740 bytes of headroom for a strictly better algorithm with IDENTICAL
    ordering semantics.

    A NOTE ON THE EXPECTED GAIN. An earlier estimate put the achievable
    high-water at roughly 96,000. That is not reachable, and the reason is
    worth recording so nobody re-derives it: the blocks are INDIVISIBLE and the
    slices must stay CONSECUTIVE, so the partition is quantised by the block
    sizes. The largest single profile block is 41,709 bytes, and a perfectly
    even split would be 94,412 -- but no consecutive partition of these
    particular 161 blocks into 16 parts achieves a maximum below 104,270. That
    figure is the true optimum, proved by the binary search below: 104,269
    requires 17 slots.

    HOW IT WORKS, IN TWO STEPS
    --------------------------
    1. Binary search the smallest feasible maximum. For a candidate cap, a
       single greedy left-to-right pass gives the minimum number of slots
       needed; the smallest cap needing <= N slots is the optimum, because
       feasibility is monotone in the cap.

    2. Among the many partitions that achieve that maximum, choose the most
       even one, by dynamic programming on the sum of squared slot sizes
       subject to every slot <= cap and exactly N slots. Step 1 alone would
       leave the trailing slots nearly empty; step 2 spreads the slack without
       touching the maximum. 161 blocks x 16 slots is a few hundred thousand
       operations, once, at generation time.

    ORDERING IS UNCHANGED, BY CONSTRUCTION
    --------------------------------------
    Slots remain consecutive slices of the emission order, and the loader calls
    them in fixed numeric order, so vector index == eFILM_PROFILE value ==
    film_names.txt line, exactly as before. Every slot file's CONTENT changes;
    the concatenation does not. film_enum.hpp and film_names.txt must therefore
    come out byte-identical, and the caller asserts that.

    Deterministic: the same database always produces the same files.
    """
    sizes = [len(b.encode("utf-8")) for b in blocks]
    n     = len(sizes)

    if 0 == n:
        return [[] for _ in range(N_DATA_SLOTS)]

    # -- step 1: smallest feasible maximum ---------------------------------
    def slots_needed(cap: int) -> int:
        count, cur = 1, 0
        for s in sizes:
            if s > cap:
                return n + 1          # infeasible: one block exceeds the cap
            if cur + s > cap:
                count += 1
                cur = s
            else:
                cur += s
        return count

    lo, hi = max(sizes), sum(sizes)
    while lo < hi:
        mid = (lo + hi) // 2
        if slots_needed(mid) <= N_DATA_SLOTS:
            hi = mid
        else:
            lo = mid + 1
    cap = lo

    # -- step 2: most even partition achieving that maximum ----------------
    pre = [0] * (n + 1)
    for i, s in enumerate(sizes):
        pre[i + 1] = pre[i] + s

    INF = float("inf")
    dp     = [[INF] * (n + 1) for _ in range(N_DATA_SLOTS + 1)]
    choice = [[-1]  * (n + 1) for _ in range(N_DATA_SLOTS + 1)]
    dp[0][0] = 0

    for k in range(1, N_DATA_SLOTS + 1):
        for i in range(0, n + 1):
            for j in range(i, -1, -1):
                w = pre[i] - pre[j]
                if w > cap:
                    break                       # further j only make it bigger
                if dp[k - 1][j] == INF:
                    continue
                v = dp[k - 1][j] + w * w
                if v < dp[k][i]:
                    dp[k][i]     = v
                    choice[k][i] = j

    if dp[N_DATA_SLOTS][n] == INF:
        # Cannot happen: step 1 proved a partition into N slots exists at this
        # cap. Kept as a hard failure rather than a silent fallback, because a
        # silent fallback here would emit a differently-ordered database.
        raise RuntimeError(
            "slot partitioner: no feasible partition at the proven cap "
            f"{cap}; this indicates a bug in the binary search, not a "
            "database that has outgrown its slots")

    cuts, i = [], n
    for k in range(N_DATA_SLOTS, 0, -1):
        j = choice[k][i]
        cuts.append((j, i))
        i = j
    cuts.reverse()

    return [blocks[a:b] for a, b in cuts]


