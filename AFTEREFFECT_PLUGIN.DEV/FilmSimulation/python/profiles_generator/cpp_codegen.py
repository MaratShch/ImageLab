def _f(x: float) -> str:
    """Format a float as an exact C++ float literal.

    ``np.format_float_positional(np.float32(x), unique=True)`` emits the
    shortest decimal that round-trips through IEEE float32 (up to 9
    significant digits), fixing audit finding PY-01 -- the old ``%.6g``
    truncated values such as 3.321928. The decimal point is not optional:
    numpy renders 36.0 as ``36.``, which is a valid literal but ugly, and a
    bare ``36`` would make ``36f`` invalid, so both cases are normalised.
    """
    s = np.format_float_positional(np.float32(x), unique=True)
    if s.endswith("."):
        s += "0"
    elif "." not in s:
        s += ".0"
    return s + "f"


def _d(x: float) -> str:
    """Format a float as an exact C++ double literal.

    Same shortest-roundtrip idea as ``_f`` but through IEEE float64 and
    without the ``f`` suffix. Used for the schema-v3 spectral tables, which
    are declared ``double`` (offline generation, storage free; measurement
    accuracy, stated per stock, remains the real precision bound).
    """
    s = np.format_float_positional(np.float64(x), unique=True)
    if s.endswith("."):
        s += "0"
    elif "." not in s:
        s += ".0"
    return s


