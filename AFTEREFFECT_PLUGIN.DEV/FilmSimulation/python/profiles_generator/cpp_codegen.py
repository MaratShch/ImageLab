"""
C++ table generation for the film profile database.

Emits ``film_profiles.hpp`` / ``film_profiles.cpp`` mirroring the Python
dataclasses one-for-one, so a C++ renderer consumes exactly the same physical
parameters the Python reference implementation used. Nothing here computes
anything -- it is a serialiser, and the Python side stays the single source of
truth.

Notes carried over from earlier revisions, still true:

* ``features`` is a real ``enum class`` bitmask, not a string. The old string
  form invited ``features.find("HALATION")``, which also matches
  ``HAS_BLUE_HALATION`` -- a live bug in the original script.
* Every field carries its physical unit in the comment, because a bare
  ``float freq_r`` is impossible to use correctly without knowing whether it is
  pixels, micrometres or cycles per millimetre.
* The header ships the reference formulae for the characteristic curve, the
  MTF and the grain spectrum, so a C++ port cannot silently diverge from the
  Python implementation.

Schema version 2 additions (2026-07 domain review):

* New structs TemporalSpec / ReciprocitySpec / AgingSpec / Provenance and the
  calibration metadata fields on FilmProfile; extended GrainSpec, MTFSpec,
  PrintStock and FilmFormat. All appended after the existing fields, so the
  aggregate initialiser order of the v1 prefix is unchanged.
* Floats are emitted with ``np.format_float_positional(np.float32(x),
  unique=True)`` -- the shortest decimal that round-trips through float32 --
  instead of the previous 6-significant-digit ``%.6g`` (audit finding PY-01,
  which truncated values such as 3.321928).
* Every emitted profile literal is preceded by a data-source comment block
  (official document title, publisher and year from Provenance.sources, plus
  the evidence tier), so the generated .cpp is auditable without the Python
  side. Print stocks get a one-line equivalent.

Requires Python 3.12+ and numpy (for exact float32 literal formatting).
"""

