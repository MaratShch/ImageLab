_ENTRY_RX = re.compile(r'^        // --- ([A-Z0-9_]+) -', re.M)
_NAME_RX = re.compile(r'^            "([A-Z0-9_]+)",$', re.M)


def write_film_names(cpp_path: Path, txt_path: Path,
                     separator: bool = True) -> int:
    """Emit the film-name list consumed by the C++ effect-panel listbox.

    Order is taken by parsing the ALREADY-WRITTEN film_profiles.cpp rather than
    by re-walking FILM_PROFILES. That is deliberate: the listbox indexes into
    GetFilmDatabase()'s std::vector, so line N here must be element N-1 there.
    Re-deriving from FILM_PROFILES would only be *assumed* equal; reading the
    emitted table back makes it equal by construction, so a future reordering
    inside the emitter cannot silently desynchronise panel and database.

    Must therefore be called after the .cpp is on disk.

    Parsing is deliberately belt-and-braces: entry boundaries come from the
    per-entry header comment, the name from the first quoted upper-case token
    inside each entry, and the two lists must agree. A bare scan of quoted
    upper-case tokens would NOT work -- other fields (StockKind, SCAN_DI, ...)
    are emitted in the same shape at the same indent.

    Format: display name (underscores turned into spaces) in double quotes,
    one per line, LF endings, plain ASCII, no comments.

    Separator (2026-08-13, owner request): by DEFAULT every line except the
    LAST carries a trailing "|" INSIDE the closing quote -- "NAME|". The file
    is consumed as adjacent C++ string literals, and concatenation then
    yields the single "A|B|...|Z" string an After Effects popup expects,
    with no separator after the final item. ``separator=False`` (the
    --no_separator command-line flag) restores the previous pipe-free
    format. Line order is the GetFilmDatabase() vector order in BOTH modes;
    only the trailing character differs.
    """
    names = parse_vector_names(cpp_path)
    out = []
    for i, n in enumerate(names):
        disp = n.replace("_", " ")
        try:
            disp.encode("ascii")
        except UnicodeEncodeError:
            raise ValueError(f"{n}: name is not ASCII, cannot go in the "
                             f"plain-ASCII listbox file")
        # "|" after the name, inside the quotes, on every line but the last.
        sep = "|" if (separator and i < len(names) - 1) else ""
        out.append('"%s%s"' % (disp, sep))
    txt_path.write_text("\n".join(out) + "\n", encoding="ascii", newline="\n")
    return len(out)


def parse_vector_names(cpp_path: Path) -> list:
    """Return the profile names in GetFilmDatabase() std::vector order.

    Single source of truth for every index-bearing artefact (listbox TXT and
    film_enum.hpp), read back out of the emitted .cpp so their indices cannot
    drift from the database.
    """
    # The table now lives in the fixed data-slot files; read them back in
    # slot order. Concatenating in that order IS the vector order, because
    # the loader calls AppendProfiles_01..NN in the same fixed sequence.
    d = Path(cpp_path).parent
    parts = []
    for i in range(1, N_DATA_SLOTS + 1):
        p = d / f"film_profiles_data_{i:02d}.cpp"
        if not p.is_file():
            raise FileNotFoundError(f"data slot missing: {p.name} -- "
                                    f"generate() must write all slots first")
        parts.append(p.read_text(encoding="utf-8"))
    table = "".join(parts)

    bounds = [(m.start(), m.group(1)) for m in _ENTRY_RX.finditer(table)]
    offsets = [b[0] for b in bounds] + [len(table)]

    names = []
    for i, (_, declared) in enumerate(bounds):
        chunk = table[offsets[i]:offsets[i + 1]]
        found = _NAME_RX.search(chunk)
        if found is None:
            raise ValueError(f"{declared}: no name field found in its entry")
        if found.group(1) != declared:
            raise ValueError(
                f"entry header says {declared} but its first name field says "
                f"{found.group(1)} -- emitter layout changed")
        names.append(declared)

    expected = len(FILM_PROFILES)
    if len(names) != expected:
        raise ValueError(
            f"parsed {len(names)} entries from the emitted vector but "
            f"FILM_PROFILES holds {expected}")
    return names


