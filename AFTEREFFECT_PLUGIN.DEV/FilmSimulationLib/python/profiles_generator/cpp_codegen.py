def _humanize(txt: str, limit: int, capital: bool):
    """First sentence of a comment, in plain words; None when it should go."""
    t = txt.replace("⚠", " ").replace("`", "")
    if re.search(r"[Ѐ-ӿ]", t) or t.lstrip().startswith("["):
        return None
    t = re.sub(r"\s*\[[^\]]*\]", "", t)
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"^[-=#*~|>:.\s]+", "", t)
    t = re.sub(r"^(?:19|20)\d\d-\d\d(?:-\d\d)?[a-z]?\s*[:,]\s*", "", t)
    t = re.sub(r"^[\\@](?!return)\w+\s+", "", t)
    if re.match(r"(?i)(schema v\d+|v\d+\b|20\d\d-\d\d)", t) and ":" not in t[:40]:
        return None
    t = re.sub(r"(?i)^schema v\d+[^:]*:\s*", "", t)
    t = re.sub(r"\s*\([^()]*(?:schema v\d+|\b(?:19|20)\d\d-\d\d|owner)[^()]*\)", "", t,
               flags=re.I)
    t = re.sub(r"^[\s.,;:-]+", "", t)
    for ab in ("i.e.", "e.g.", "cf.", "vs.", "approx.", "etc.", "No.", "Fig.", "p."):
        t = t.replace(ab, ab.replace(".", "\x00"))
    m = re.match(r"(.+?[.!?])(?=\s|$)", t)
    first = (m.group(1) if m else t).replace("\x00", ".")
    first = re.sub(r"\s*[-=]{3,}.*$", "", first)
    first = re.sub(r"\b[A-Z]{2,}\b",
                   lambda w: w.group(0) if w.group(0) in _BRIEF_ACRONYMS
                   else w.group(0).lower(), first)
    first = re.sub(r"(?<=\w )A (?=[a-z])", "a ", first)
    first = re.sub(r"\s+", " ", first).strip(" -:;,")
    if len(re.findall(r"[A-Za-z]{2,}", first)) < 2 or len(first) > limit:
        return None
    if capital:
        first = first[0].upper() + first[1:]
    return first


def _scan_lines(src: str):
    """Split C++ source into lines of (code, line_comment_or_None). Strings and
    character literals stay in the code; /* */ comments become a space."""
    lines, code, com = [], [], None
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c == "\n":
            lines.append(("".join(code), com))
            code, com = [], None
            i += 1
            continue
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            code.append(src[i:j + 1])
            i = j + 1
            continue
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            com = src[i:j]
            i = j
            continue
        if src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            parts = src[i:j].split("\n")
            code.append(" ")
            for _ in parts[1:]:
                lines.append(("".join(code), com))
                code, com = [], None
            i = j
            continue
        code.append(c)
        i += 1
    lines.append(("".join(code), com))
    return lines


def _comment_body(com: str) -> tuple:
    m = re.match(r"(//+<?)\s?(.*)$", com)
    return m.group(1), m.group(2)


def brief_cpp(text: str, name: str = None, keep_sentinel: bool = False) -> str:
    """The generated C++ `text` with brief, human comments (see above).
    keep_sentinel: leave "//@ " lines as they are (a slot unit that is briefed
    again when its whole file is written)."""
    def sentinel(t):
        return re.sub(r"(?m)^(\s*)//@ ", r"\1// ", t)
    if not BRIEF_COMMENTS:
        return sentinel(text)
    slot = bool(name) and name.startswith("film_profiles_data_")
    head, body = "", text
    if text.startswith(COPYRIGHT_NOTICE):
        head, body = COPYRIGHT_NOTICE, text[len(COPYRIGHT_NOTICE):]
    raw = body.split("\n")
    scanned = _scan_lines(body)
    out = []
    summary_done = not (name in FILE_SUMMARIES)
    i = 0
    while i < len(scanned):
        code, com = scanned[i]
        line = raw[i] if i < len(raw) else code
        if com is not None and not code.strip():
            if _BRIEF_KEEP_RX.match(line):
                ms = re.match(r"^(\s*//\s*schema_version \d+)", line)
                out.append(ms.group(1) if ms else line.rstrip())
                i += 1
                continue
            if com.startswith("//@ "):
                out.append(line.rstrip() if keep_sentinel
                           else line.replace("//@ ", "// ", 1).rstrip())
                i += 1
                continue
            # a run of whole-line comments
            indent = re.match(r"\s*", line).group(0)
            pre, _ = _comment_body(com)
            texts = []
            while (i < len(scanned) and scanned[i][1] is not None
                   and not scanned[i][0].strip()
                   and not _BRIEF_KEEP_RX.match(raw[i])
                   and not scanned[i][1].startswith("//@ ")):
                texts.append(_comment_body(scanned[i][1])[1])
                i += 1
            if not slot:
                h = _humanize(" ".join(texts), 110, True)
                if h:
                    out.append(f"{indent}{'///' if pre.startswith('///') else '//'} {h}")
            continue
        if com is not None:
            # code with a trailing comment; "///<" continuation lines join it
            pre, txt = _comment_body(com)
            texts = [txt]
            j = i + 1
            while (pre.endswith("<") and j < len(scanned)
                   and not scanned[j][0].strip() and scanned[j][1] is not None
                   and scanned[j][1].lstrip().startswith("///<")):
                texts.append(_comment_body(scanned[j][1])[1])
                j += 1
            h = None if slot else _humanize(" ".join(texts), 90, False)
            out.append(code.rstrip() + (f"  {pre} {h}" if h else ""))
            i = j
            continue
        out.append(code.rstrip())
        i += 1
    # the file summary goes under the last stamp line before the first code line
    if not summary_done:
        first_code = next((k for k, ln in enumerate(out)
                           if ln.strip() and not ln.lstrip().startswith("//")), len(out))
        stamps = [k for k in range(first_code) if _BRIEF_STAMP_RX.match(out[k])]
        at = (stamps[-1] + 1) if stamps else 0
        out.insert(at, "// " + FILE_SUMMARIES[name])
    # collapse blank runs
    res, blank = [], False
    for ln in out:
        if not ln.strip():
            if blank:
                continue
            blank = True
        else:
            blank = False
        res.append(ln)
    return head + "\n".join(res)


def _distribute_capped(units: list) -> list:
    """Fill the slots in emission order: a new slot starts when the current
    one already holds MAX_PROFILES_PER_SLOT profile blocks or the next unit
    would push the file past SLOT_FILE_LIMIT (minus the slot header). The
    resulting count must equal N_DATA_SLOTS -- a change in the database that
    moves it is reported, never absorbed silently."""
    budget = SLOT_FILE_LIMIT - 4_000          # header, namespaces, signature
    slots, cur, n_blk, size = [], [], 0, 0
    for kind, txt in units:
        w = len(txt.encode("utf-8"))
        full = size + w > budget or (kind == "blk" and n_blk >= MAX_PROFILES_PER_SLOT)
        if cur and full:
            slots.append(cur)
            cur, n_blk, size = [], 0, 0
        cur.append((kind, txt))
        size += w
        n_blk += kind == "blk"
    if cur:
        slots.append(cur)
    if len(slots) != N_DATA_SLOTS:
        raise RuntimeError(
            f"capped slot fill ({MAX_PROFILES_PER_SLOT} profiles per file) needs "
            f"{len(slots)} data slots, N_DATA_SLOTS is {N_DATA_SLOTS}: set "
            f"N_DATA_SLOTS to {len(slots)} in cpp_codegen.py (CMake globs "
            f"src/*.cpp; a hand-listed VS project must list the files)")
    return slots


