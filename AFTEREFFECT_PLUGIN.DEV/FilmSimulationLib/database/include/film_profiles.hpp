/// Grain-sigma multiplier at a given density -- the one definition.
inline float FilmGrainSigma(const GrainSpec& g, float dmin, float dmax, float D)
{
    // A measured table replaces the anchors outright.
    if (g.sigma_shape_measured && g.sigma_shape_mid > 0.0f && g.sigma_pts_n >= 2) {
        const int n = g.sigma_pts_n;
        const float* xs = g.sigma_pts_d;
        const float* ys = g.sigma_pts_s;
        const float dRef = dmin + 1.0f;
        if (xs[n-1] > xs[0] + 1.0f && dRef < xs[n-1]) {
            float v = ys[n-1], mid = ys[n-1];
            if (D <= xs[0]) { v = ys[0]; }
            else {
                for (int i = 1; i < n; ++i) {
                    if (D <= xs[i]) {
                        const float t = (xs[i] > xs[i-1])
                                      ? (D - xs[i-1]) / (xs[i] - xs[i-1]) : 0.0f;
                        v = ys[i-1] + t * (ys[i] - ys[i-1]);
                        break;
                    }
                }
            }
            if (dRef <= xs[0]) { mid = ys[0]; }
            else {
                for (int i = 1; i < n; ++i) {
                    if (dRef <= xs[i]) {
                        const float t = (xs[i] > xs[i-1])
                                      ? (dRef - xs[i-1]) / (xs[i] - xs[i-1]) : 0.0f;
                        mid = ys[i-1] + t * (ys[i] - ys[i-1]);
                        break;
                    }
                }
            }
            return (mid > 0.0f) ? (v / mid) : v;
        }
    }
    if (g.sigma_pts_n < 2 && g.sigma_shape_measured && g.sigma_shape_mid > 0.0f) {
        const float dToe = (g.sigma_shape_toe_at > 0.0f) ? g.sigma_shape_toe_at : dmin;
        const float dTop = (g.sigma_shape_dmax_at > 0.0f) ? g.sigma_shape_dmax_at : dmax;
        const float dRef = dmin + 1.0f;  // net density 1.0 -- see the note above
        if (dTop > dToe && dRef < dTop) {
            // At most four anchors, kept sorted by density.
            float xs[4], ys[4];
            int n = 0;
            xs[n] = dToe;  ys[n++] = g.sigma_shape_toe;
            xs[n] = 1.0f;  ys[n++] = g.sigma_shape_mid;
            xs[n] = dTop;  ys[n++] = g.sigma_shape_dmax;
            if (g.sigma_shape_peak > 0.0f && g.sigma_shape_peak_at > 0.0f) {
                xs[n] = g.sigma_shape_peak_at;  ys[n++] = g.sigma_shape_peak;
            }
            for (int i = 1; i < n; ++i) {
                const float kx = xs[i], ky = ys[i];
                int j = i - 1;
                while (j >= 0 && xs[j] > kx) { xs[j+1] = xs[j]; ys[j+1] = ys[j]; --j; }
                xs[j+1] = kx; ys[j+1] = ky;
            }
            float v = ys[n-1], mid = ys[n-1];
            if (D <= xs[0]) { v = ys[0]; }
            else {
                for (int i = 1; i < n; ++i) {
                    if (D <= xs[i]) {
                        const float t = (xs[i] > xs[i-1])
                                      ? (D - xs[i-1]) / (xs[i] - xs[i-1]) : 0.0f;
                        v = ys[i-1] + t * (ys[i] - ys[i-1]);
                        break;
                    }
                }
            }
            if (dRef <= xs[0]) { mid = ys[0]; }
            else {
                for (int i = 1; i < n; ++i) {
                    if (dRef <= xs[i]) {
                        const float t = (xs[i] > xs[i-1])
                                      ? (dRef - xs[i-1]) / (xs[i] - xs[i-1]) : 0.0f;
                        mid = ys[i-1] + t * (ys[i] - ys[i-1]);
                        break;
                    }
                }
            }
            return (mid > 0.0f) ? (v / mid) : v;
        }
    }
    const float num = std::sqrt(((D - dmin) > 0.0f ? (D - dmin) : 0.0f) + g.fog_grain);
    const float den = std::sqrt(1.0f + g.fog_grain);
    return (den > 0.0f) ? (num / den) : num;
}

