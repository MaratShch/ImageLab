/// Modulation transfer at a spatial frequency -- the one definition.
inline float FilmMtfResponse(const MTFSpec& m, int channel, float f)
{
    const float f50 = (channel == 0) ? m.f50_r : (channel == 2) ? m.f50_b : m.f50_g;
    if (f50 <= 0.0f) {
        return 1.0f;
    }
    const float x = f / f50;
    if (m.mtf_measured && m.mtf_rolloff_q > 0.0f) {
        return 1.0f / (1.0f + std::pow(x, m.mtf_rolloff_q));
    }
    return std::exp(-0.6931471805599453f * x * x);
}

