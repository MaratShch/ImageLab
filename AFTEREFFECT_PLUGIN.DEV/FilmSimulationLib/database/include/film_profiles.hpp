/// Sampled spectral sensitivity curves digitised from manufacturer datasheet plots.
struct InterimageSpec {
    double a_rg;  ///< green layer's development inhibiting the red layer
    double a_rb;  ///< blue layer -> red layer (far pair, weaker)
    double a_gr;  ///< red layer -> green layer
    double a_gb;  ///< blue layer -> green layer
    double a_br;  ///< red layer -> blue layer (far pair, weaker)
    double a_bg;  ///< green layer -> blue layer
    int    iterations;  ///< fixed-point passes; 0 disables
    /// Where along the curve the coupling acts.
    double density_weighting;

    bool active (void) const noexcept {
        return iterations > 0
            && (a_rg != 0.0 || a_rb != 0.0 || a_gr != 0.0
                || a_gb != 0.0 || a_br != 0.0 || a_bg != 0.0);
    }
};

/// Emulsion coating and camera-gate defects.
struct CoatingSpec {
    /// RMS fractional sensitivity variation, 0.035 = 3.5 % one sigma.
    double coating_sigma;
    double coating_corr_across_mm;  ///< correlation length across the web, mm
    double coating_corr_along_mm;  ///< correlation length along the web, mm
    double buckle_mtf_loss;
    /// Extra density at the film edge: light leaking past the edge of the roll plus development edge effects.
    double edge_fog_density;
    double edge_fog_mm;  ///< decay length inward from the edge, mm

    bool hasCoatingField (void) const noexcept { return coating_sigma > 0.0; }
    bool hasBuckle       (void) const noexcept { return buckle_mtf_loss > 0.0; }
    bool hasEdgeFog      (void) const noexcept {
        return edge_fog_density > 0.0 && edge_fog_mm > 0.0;
    }
};

