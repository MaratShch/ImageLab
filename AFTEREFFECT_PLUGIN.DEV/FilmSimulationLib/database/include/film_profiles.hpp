struct ProcessingFamily {
    std::vector<DevelopmentPoint> points;
    /// D ln(time) / d(degrees C) at constant contrast, negative.
    double temperature_coeff_per_c;
    /// The developer, and its dilution, that the source'S own characteristic curve was measured in.
    std::string reference_developer;
    std::string reference_dilution;
    std::string reference_edition;
    // One law per developer, when the family spans more than one.
    std::vector<DevelopmentLaw> laws;
    // Developer exhaustion tables.
    std::vector<DevelopmentCapacity> capacity;
    // Developer rows (Developer control).
    std::vector<DeveloperGrainPoint> grain_points;
    /// The row the stored profile corresponds to; selecting it is the identity.
    std::string grain_reference_developer;
    double gamma_infinity;
    double dev_rate_k;  ///< per minute
    double induction_t0_min;
    /// Development-rate ratio per +10 degC (Glafkides §86).
    double temp_q10;

    bool hasData() const { return !points.empty(); }
    bool hasRateLaw() const { return gamma_infinity > 0.0 && dev_rate_k > 0.0; }
};

